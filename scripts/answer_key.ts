// Regenerates ANSWER_KEY.md from the game's own question pool and checks the rules.
// Run: npm run answer-key
import assert from 'node:assert/strict';
import fs from 'node:fs';
import aliasFile from '../data/aliases.json';
import { aliases, answers, judge, names, questions } from '../lib/data';
import { makeQuestions, score, suggest, TYPES } from '../lib/game';

// Self-checks
assert.equal(score([5], 5), 1000);
assert.deepEqual([0, 0, 10, 20].map((a, _, all) => score(all, a)), [1000, 1000, 400, 100]);
assert.equal(new Set(questions.map(q => q.id)).size, questions.length, 'duplicate question ids');
for (const q of questions) assert.ok(answers(q.id).length >= 5, q.id + ' has fewer than 5 answers');
for (const t of TYPES) assert.ok(questions.some(q => q.type === t), 'no questions of type ' + t);
const climb = makeQuestions(questions, '2026-11-23');
assert.deepEqual(climb, makeQuestions(questions, '2026-11-23'), 'daily climb not deterministic');
assert.equal(new Set(climb.map(q => q.type)).size, 7, 'climb not balanced by type');
let dead = 0, recent = 0;
for (let i = 0; i < 5000; i++) {
  const c = makeQuestions(questions, 's' + i);
  assert.equal(c.length, 7, 'climb must have 7 questions');
  assert.ok(c.some(q => q.type === 'teammate'), 'every climb must include a teammate question');
  for (const q of c) { dead += +q.dead; recent += +q.recent; }
}
assert.equal(judge('virat-kohli--teammate', 'AB de Villiers').correct, true);
assert.equal(judge('virat-kohli--teammate', 'Virat Kohli').correct, false, 'a star is not their own teammate');
assert.ok(questions.some(q => q.prompt === 'Name an IPL teammate of Amit Mishra'), 'bracketed names are cleaned in prompts');
assert.notEqual((judge('mumbai-indians', 'Amit Mishra') as { reason?: string }).reason, 'NO IPL PLAYER BY THAT NAME');
assert.ok(Math.abs(recent / 35000 - 0.5) < 0.02, 'recent share off 50%: ' + recent / 35000);
assert.ok(dead / 35000 < 0.18, 'defunct-team share above target: ' + dead / 35000);
assert.equal(judge('mumbai-indians', 'rohit sharma').correct, true);
assert.equal(judge('mumbai-indians', 'xyzzy').correct, false);
assert.equal(Object.keys(aliases).length, Object.keys(aliasFile).length, 'a nickname points to a player not in the data');
assert.equal(judge('chennai-super-kings', 'Thala').correct, true, 'nicknames should be accepted');
const s = (t: string) => suggest(t, names, aliases)?.name;
for (const [typed, want] of [['thala', 'MS Dhoni'], ['hitman', 'Rohit Sharma'], ['dhony', 'MS Dhoni'], ['viraat kohli', 'Virat Kohli'], ['jasprit bumra', 'Jasprit Bumrah'], ['bumrah', 'Jasprit Bumrah'], ['ms dh', 'MS Dhoni']]) assert.equal(s(typed), want, typed);
assert.equal(s('MS Dhoni'), undefined, 'no suggestion for a correct name');
assert.equal(s('q'), undefined);

// Answer key
const label: Record<string, string> = { teammate: 'Teammate of a star', squad: 'Franchise squad', pair: 'Two franchises', role: 'Role', bowling: 'Bowling style', hand: 'Batting hand', season: 'Single season', journeyman: 'Franchise count' };
let md = '# IPL Krillion answer key\n\nGenerated by `npm run answer-key` from data/players.json. ' + questions.length + ' questions; each climb has a teammate question plus 6 other types. Answers sorted best score first.\n\n';
for (const t of TYPES) {
  const qs = questions.filter(q => q.type === t);
  md += '# ' + label[t] + ' (' + qs.length + ' questions)\n\n';
  for (const q of qs) {
    const ok = answers(q.id);
    const rows = ok.map(p => ({ p, s: (judge(q.id, p.name) as { points: number }).points })).sort((a, b) => b.s - a.s || a.p.name.localeCompare(b.p.name));
    md += '## ' + q.prompt + (q.recent ? ' · recent' : '') + '\n\n' + ok.length + ' valid answers.\n\n| Player | IPL matches | Score (m) |\n|---|---:|---:|\n' + rows.map(({ p, s }) => '| ' + p.name + ' | ' + (p.apps ?? '?') + ' | ' + s + ' |').join('\n') + '\n\n';
  }
}
fs.writeFileSync(new URL('../ANSWER_KEY.md', import.meta.url), md);
console.log('checks passed;', questions.length, 'questions:', TYPES.map(t => t + ' ' + questions.filter(q => q.type === t).length).join(', '));
